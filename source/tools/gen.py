import json, numpy as np
from shapely.geometry import Polygon, MultiPolygon, box
from shapely.ops import unary_union
from parse import load
L = load(n=12)
def evenodd(polys):
    acc = Polygon()
    for p in polys:
        acc = acc.symmetric_difference(Polygon(p).buffer(0))
    return acc
sil = evenodd(L['silhouette_letters_plus_shadow'])
let = evenodd(L['letters'])
K = 0.022            # world units per mm
CX, TOPY = 63.0, 26.4  # mm: middle of the S top -> world x = GRIP_X, its top -> y = 0
GRIP_X = 0.2
R_MM = 0.04 / K      # rail radius in plane
# weld the little notch in the top of the S so the perch is one continuous rail
weld = Polygon([(55.5, 30.5), (56.5, 26.6), (60, 26.2), (63.5, 26.6), (64.5, 30.5)]).buffer(0.6)
body = unary_union([sil, weld]).buffer(0.05)
# the perch stretch: the top of the S, evened out into one smooth rail (the raw trace has
# 2-3 mm lumps, the size of a bird's foot): cut what pokes above a gentle arch, fill below it
XA, XB = 53.8, 73.6
def yarch(xm):
    return TOPY - (0.3 + 0.9 * np.sin(np.pi * (xm - XA) / (XB - XA)))
xs = np.linspace(XA, XB, 60)
curve = [(x, yarch(x)) for x in xs]
above = Polygon(curve + [(XB, TOPY - 8), (XA, TOPY - 8)])
band = Polygon(curve + [(XB, TOPY + 4.5), (XA, TOPY + 4.5)])
body = unary_union([body.difference(above), band.intersection(body.buffer(3))]).buffer(0.6).buffer(-0.6)
core = body.buffer(-R_MM, join_style=1, resolution=6).simplify(0.06)
letc = let.intersection(body.buffer(-(0.62 * R_MM), join_style=1, resolution=6)).buffer(-0.12, join_style=1, resolution=6).buffer(0.0).simplify(0.06)
def parts(g):
    if g.is_empty: return []
    return list(g.geoms) if hasattr(g, 'geoms') else [g]
def w(pt):
    x, y = pt
    return [round((x - CX) * K + GRIP_X, 4), round(-(y - TOPY) * K, 4)]
def shape(p, minarea):
    if p.area < minarea: return None
    ext = [w(q) for q in list(p.exterior.coords)[:-1]]
    holes = [[w(q) for q in list(h.coords)[:-1]] for h in p.interiors if Polygon(h).area > minarea]
    return {'o': ext, 'h': holes}
bodyS = [s for s in (shape(p, 0.5) for p in parts(core)) if s]
letS = [s for s in (shape(p, 0.5) for p in parts(letc)) if s]
npts = sum(len(s['o']) + sum(len(h) for h in s['h']) for s in bodyS)
nl = sum(len(s['o']) + sum(len(h) for h in s['h']) for s in letS)
print('body parts', len(bodyS), 'pts', npts, 'letters', len(letS), 'pts', nl)
print('area sil', round(sil.area), 'core+R', round(core.buffer(R_MM).area), 'let', round(let.area), round(letc.area))
# occupancy grid (world), 0.05 cells, of the body grown by 0.1 for flight clearance
minx, miny, maxx, maxy = body.bounds
X0, Y1 = w((minx, miny)); X1, Y0 = w((maxx, maxy))
C = 0.05
nx = int(np.ceil((X1 - X0) / C)) + 1; ny = int(np.ceil((Y1 - Y0) / C)) + 1
grow = body.buffer(0.1 / K)
from shapely import prepared
from shapely.geometry import Point
pg = prepared.prep(grow)
bits = []
for j in range(ny):
    row = ''
    for i in range(nx):
        xw = X0 + i * C; yw = Y0 + j * C
        xm = (xw - GRIP_X) / K + CX; ym = TOPY - yw / K
        row += '1' if pg.contains(Point(xm, ym)) else '0'
    bits.append(row)
# top surface for checking the perch: the body's highest y at each x over the perch stretch
tops = []
for xm in np.arange(50, 78, 0.5):
    ln = body.intersection(box(xm - 0.01, -10, xm + 0.01, 200))
    if ln.is_empty: continue
    tops.append((round(w((xm, 0))[0], 3), round(-(ln.bounds[1] - TOPY) * K, 4)))
print('tops', tops)
bb = [w((minx, maxy)), w((maxx, miny))]
data = {'k': K, 'gripX': GRIP_X, 'bounds': bb, 'body': bodyS, 'letters': letS,
        'grid': {'x0': round(X0, 4), 'y0': round(Y0, 4), 'cell': C, 'nx': nx, 'ny': ny, 'rows': bits}}
ts = '// Risk Rock\'s RISK tag (Kelly Graval), traced from riskrock.com\'s "420 RISK Tag Special Drop".\n' \
     '// Used with the artist\'s permission through Vincent Strader. Generated by risk_perch/gen.py:\n' \
     '// outlines in world units (1 mm of the tag = %.3f), the top of the S at y = 0 over x = GRIP_X.\n' % K
ts += 'export const RISK_TAG = ' + json.dumps(data, separators=(',', ':')) + ' as const;\n'
open('../src/env/riskTagData.ts', 'w').write(ts)
print('ts bytes', len(ts), 'grid', nx, ny, 'bounds', bb)
